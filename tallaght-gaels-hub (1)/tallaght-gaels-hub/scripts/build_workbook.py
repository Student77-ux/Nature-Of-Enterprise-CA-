def category_block(start_row, heading, column_name, values):
    ws.cell(row=start_row, column=1, value=heading).font = Font(name=FONT, bold=True, size=11, color=GREEN)
    hdr_row = start_row + 1
    for j, h in enumerate(["Category", "Matches", "Share", "Average attendance",
                           "Highest attendance", "Lowest attendance"], start=1):
        ws.cell(row=hdr_row, column=j, value=h)
    style_header(ws, row=hdr_row, last_col=6, fill=INK)
    rng = f"'Raw Data'!${COL[column_name]}${FIRST}:${COL[column_name]}${LAST}"
    for i, v in enumerate(values):
        r = hdr_row + 1 + i
        ws.cell(row=r, column=1, value=v)
        ws.cell(row=r, column=2, value=f"=COUNTIF({rng},$A{r})")
        ws.cell(row=r, column=3, value=f"=B{r}/{N}")
        ws.cell(row=r, column=4, value=f"=AVERAGEIF({rng},$A{r},{att})")
        ws.cell(row=r, column=5, value=f"=SUMPRODUCT(MAX(({rng}=$A{r})*{att}))")
        ws.cell(row=r, column=6, value=f"=SUMPRODUCT(MIN(({rng}=$A{r})*{att}+({rng}<>$A{r})*1000000))")
        ws.cell(row=r, column=3).number_format = "0.0%"
        for cc in (4, 5, 6):
            ws.cell(row=r, column=cc).number_format = "#,##0"
        for c in range(1, 7):
            ws.cell(row=r, column=c).font = Font(name=FONT, size=10)
            ws.cell(row=r, column=c).border = BOX
    return hdr_row + 1 + len(values)


