# ------------------------------------------------------------------ helpers


def style_header(ws, row=1, last_col=None, fill=GREEN):
    last_col = last_col or ws.max_column
    for c in range(1, last_col + 1):
        cell = ws.cell(row=row, column=c)
        cell.font = Font(name=FONT, bold=True, color="FFFFFF", size=10)
        cell.fill = PatternFill("solid", fgColor=fill)
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BOX


def title(ws, text, subtitle=None):
    ws["A1"] = text
    ws["A1"].font = Font(name=FONT, bold=True, size=14, color=GREEN)
    if subtitle:
        ws["A2"] = subtitle
        ws["A2"].font = Font(name=FONT, italic=True, size=9, color="4A5A50")


def widths(ws, spec):
    for letter, w in spec.items():
        ws.column_dimensions[letter].width = w


def base_font(ws):
    for row in ws.iter_rows():
        for cell in row:
            if cell.font is None or cell.font.name != FONT:
                cell.font = Font(name=FONT, size=cell.font.size or 10,
                                 bold=cell.font.bold, italic=cell.font.italic,
                                 color=cell.font.color)


